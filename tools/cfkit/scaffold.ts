export const GENERATED_MARKER = "// Generated by cfkit scaffold endpoint";

export type ScaffoldFile = Readonly<{ path: string; content: string }>;

export type ScaffoldEdit = Readonly<{
  path: string;
  anchor: string;
  placement: "line-before" | "line-after";
  lines: readonly string[];
}>;

export type ScaffoldPlan = Readonly<{
  kind: "feature" | "endpoint";
  description: string;
  files: readonly ScaffoldFile[];
  edits: readonly ScaffoldEdit[];
  moveOperation: string | undefined;
  nextSteps: readonly string[];
}>;

export type CoverageManifest = Readonly<Record<string, unknown>>;

const FEATURE_NAME_PATTERN = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

export function normalizeFeatureName(raw: string): string {
  const name = raw
    .trim()
    .replace(/[_\s]+/g, "-")
    .replace(/[^a-zA-Z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();

  if (!FEATURE_NAME_PATTERN.test(name)) {
    throw new Error(
      `Feature name must be kebab-case starting with a letter (e.g. "billing" or "order-history"), got "${raw}"`,
    );
  }

  return name;
}

export function camelToKebab(value: string): string {
  return value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

export function pascalFromKebab(value: string): string {
  return value
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

export function camelFromPascal(value: string): string {
  return value.charAt(0).toLowerCase() + value.slice(1);
}

export function operationSlug(operationId: string): string {
  return operationId
    .split(".")
    .map((segment) => camelToKebab(segment))
    .join("-");
}

export function featureFromOperationId(operationId: string): string {
  const prefix = operationId.split(".")[0];

  if (prefix === undefined || prefix === "") {
    throw new Error(`Operation "${operationId}" has no feature prefix`);
  }

  return camelToKebab(prefix);
}

export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function stringArray(value: unknown): readonly string[] | undefined {
  if (!Array.isArray(value)) return undefined;

  return value.filter((entry): entry is string => typeof entry === "string");
}

export function readCoverageManifest(json: string): CoverageManifest {
  const parsed: unknown = JSON.parse(json);

  if (!isRecord(parsed)) {
    throw new Error("coverage.json has an unexpected shape");
  }

  if (stringArray(parsed.pending) === undefined) {
    throw new Error("coverage.json is missing the pending array");
  }

  if (stringArray(parsed.implemented) === undefined) {
    throw new Error("coverage.json is missing the implemented array");
  }

  const entries: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(parsed)) entries[key] = value;

  return entries;
}

export function coveragePending(manifest: CoverageManifest): readonly string[] {
  return stringArray(manifest.pending) ?? [];
}

export function coverageImplemented(
  manifest: CoverageManifest,
): readonly string[] {
  return stringArray(manifest.implemented) ?? [];
}

export function coverageWithOperationMoved(
  manifest: CoverageManifest,
  operationId: string,
): CoverageManifest {
  const pending = coveragePending(manifest);

  if (!pending.includes(operationId)) {
    throw new Error(
      `Operation "${operationId}" is not pending in coverage.json (already implemented?)`,
    );
  }

  const entries: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(manifest)) entries[key] = value;

  entries.pending = pending.filter((entry) => entry !== operationId);
  entries.implemented = [...coverageImplemented(manifest), operationId].sort();

  return entries;
}

export function serializeCoverageManifest(manifest: CoverageManifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function crossFeatureZoneLines(name: string, other: string): readonly string[] {
  return [
    "            {",
    `              target: "./features/${name}",`,
    `              from: "./features/${other}",`,
    '              except: ["./index.ts"],',
    "              message:",
    '                "cross-feature imports go through the feature\'s index.ts (ADR-0008)",',
    "            },",
  ];
}

function crossFeatureZoneEdits(
  name: string,
  existingFeatures: readonly string[],
): readonly ScaffoldEdit[] {
  const lines = existingFeatures.flatMap((other) => [
    ...crossFeatureZoneLines(name, other),
    ...crossFeatureZoneLines(other, name),
  ]);

  if (lines.length === 0) return [];

  return [
    {
      path: "eslint.config.mjs",
      anchor: "zones: [",
      placement: "line-after",
      lines,
    },
  ];
}

export type FeatureScaffoldOptions = Readonly<{
  exists: (path: string) => boolean;
  existingFeatures?: () => readonly string[];
}>;

export function buildFeatureScaffold(
  rawName: string,
  options: FeatureScaffoldOptions,
): ScaffoldPlan {
  const name = normalizeFeatureName(rawName);
  const base = `src/features/${name}`;

  if (options.exists(base)) {
    throw new Error(`Feature directory already exists: ${base}`);
  }

  const service = `export type FeatureDescriptor = Readonly<{ name: string }>;

// TODO: replace this slice with the real ${name} domain logic.
export function describeFeature(): FeatureDescriptor {
  return { name: "${name}" };
}
`;
  const spec = `import { describe, expect, it } from "vitest";

import { describeFeature } from "./service";

describe("${name} service", () => {
  it("describes the feature", () => {
    expect(describeFeature()).toEqual({ name: "${name}" });
  });
});
`;
  const barrel = `export { describeFeature, type FeatureDescriptor } from "./service";
`;

  const existingFeatures =
    name === ""
      ? []
      : (options.existingFeatures?.() ?? []).filter(
          (feature) => feature !== name,
        );

  return {
    kind: "feature",
    description: `capability slice ${name}`,
    files: [
      { path: `${base}/service.ts`, content: service },
      { path: `${base}/service.spec.ts`, content: spec },
      { path: `${base}/index.ts`, content: barrel },
    ],
    edits: crossFeatureZoneEdits(name, existingFeatures),
    moveOperation: undefined,
    nextSteps: [
      `Replace the TODO marker in ${base}/service.ts with real logic`,
      "Add an endpoint with `cfkit scaffold endpoint <operationId>` once the contract declares one",
    ],
  };
}

export function coverageWithOperationReturned(
  manifest: CoverageManifest,
  operationId: string,
): CoverageManifest {
  const implemented = coverageImplemented(manifest);

  if (!implemented.includes(operationId)) {
    throw new Error(
      `Operation "${operationId}" is not implemented in coverage.json (nothing to remove)`,
    );
  }

  const entries: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(manifest)) entries[key] = value;

  entries.implemented = implemented.filter((entry) => entry !== operationId);
  entries.pending = [...coveragePending(manifest), operationId].sort();

  return entries;
}


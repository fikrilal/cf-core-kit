import {
  GENERATED_MARKER,
  coverageImplemented,
  featureFromOperationId,
  normalizeFeatureName,
  operationSlug,
  pascalFromKebab,
  camelFromPascal,
  readCoverageManifest,
  type RepoAccess,
} from "./scaffold.ts";

export type RemovalEdit =
  | Readonly<{ kind: "statement"; path: string; specifier: string }>
  | Readonly<{ kind: "line"; path: string; contains: string }>
  | Readonly<{ kind: "zone-block"; path: string; feature: string }>;

export type RemovePlan = Readonly<{
  kind: "endpoint" | "feature";
  description: string;
  deleteFiles: readonly string[];
  removeDirectories: readonly string[];
  edits: readonly RemovalEdit[];
  returnOperations: readonly string[];
  coveragePath: string;
  nextSteps: readonly string[];
}>;

const PROTECTED_FEATURES = ["auth", "users"];
const COVERAGE_PATH = "tools/parity/coverage.json";

export function operationMarker(operationId: string): string {
  return `${GENERATED_MARKER} (${operationId}).`;
}

export function parseMarkedOperation(content: string): string | undefined {
  const match = /^\/\/ Generated by cfkit scaffold endpoint \((.+)\)\.$/m.exec(
    content,
  );

  return match?.[1];
}

function endpointPaths(operationId: string): Readonly<{
  feature: string;
  slug: string;
  pascal: string;
  camel: string;
  routesPath: string;
  specPath: string;
}> {
  const feature = featureFromOperationId(operationId);
  const slug = operationSlug(operationId.split(".").slice(1).join("."));
  const pascal = pascalFromKebab(slug);

  return {
    feature,
    slug,
    pascal,
    camel: camelFromPascal(pascal),
    routesPath: `src/features/${feature}/${slug}.routes.ts`,
    specPath: `src/features/${feature}/${slug}.routes.spec.ts`,
  };
}

export type RemoveEndpointInput = Readonly<{
  operationId: string;
  repo: RepoAccess;
}>;

export function buildEndpointRemoval(input: RemoveEndpointInput): RemovePlan {
  const repo = input.repo;
  const paths = endpointPaths(input.operationId);

  if (!repo.featureNames().includes(paths.feature)) {
    throw new Error(`Feature "${paths.feature}" does not exist`);
  }

  const manifest = readCoverageManifest(repo.read(COVERAGE_PATH));

  if (!coverageImplemented(manifest).includes(input.operationId)) {
    throw new Error(
      `Operation "${input.operationId}" is not implemented in coverage.json (nothing to remove)`,
    );
  }

  if (!repo.exists(paths.routesPath)) {
    throw new Error(`Generated route file not found: ${paths.routesPath}`);
  }

  if (
    !repo.read(paths.routesPath).includes(operationMarker(input.operationId))
  ) {
    throw new Error(
      `Generated marker not found in ${paths.routesPath}; refusing to remove a hand-written route`,
    );
  }

  const deleteFiles = repo.exists(paths.specPath)
    ? [paths.routesPath, paths.specPath]
    : [paths.routesPath];

  return {
    kind: "endpoint",
    description: `${input.operationId} (${paths.routesPath})`,
    deleteFiles,
    removeDirectories: [],
    edits: [
      {
        kind: "statement",
        path: "src/app.ts",
        specifier: `./features/${paths.feature}/${paths.slug}.routes`,
      },
      {
        kind: "line",
        path: "src/app.ts",
        contains: `register${paths.pascal}Routes(app);`,
      },
      {
        kind: "statement",
        path: "tools/contract/emit.entry.ts",
        specifier: `../../src/features/${paths.feature}/${paths.slug}.routes`,
      },
      {
        kind: "line",
        path: "tools/contract/emit.entry.ts",
        contains: `register${paths.pascal}Routes(app);`,
      },
      {
        kind: "line",
        path: "tools/contract/emit.entry.ts",
        contains: `...${paths.camel}Operations,`,
      },
    ],
    returnOperations: [input.operationId],
    coveragePath: COVERAGE_PATH,
    nextSteps: [
      `Run \`npm run verify:ci\` to confirm the operation left the contract surface`,
    ],
  };
}

export type RemoveFeatureInput = Readonly<{
  rawName: string;
  repo: RepoAccess;
  forceCore: boolean;
  force: boolean;
}>;

function isScaffoldTrio(file: string, content: string): boolean {
  if (file.endsWith("/service.ts")) {
    return content.includes("// TODO: replace this slice with the real");
  }

  if (file.endsWith("/service.spec.ts")) {
    return content.includes('service", () => {');
  }

  if (file.endsWith("/index.ts")) {
    return content.includes('from "./service"');
  }

  return false;
}

function collectFeatureArtifacts(
  input: Readonly<{
    name: string;
    files: readonly string[];
    repo: RepoAccess;
    force: boolean;
  }>,
): Readonly<{
  operations: readonly string[];
  edits: readonly RemovalEdit[];
  unmarked: readonly string[];
}> {
  const operations: string[] = [];
  const edits: RemovalEdit[] = [];
  const unmarked: string[] = [];

  for (const file of input.files) {
    const content = input.repo.read(file);
    const operation = parseMarkedOperation(content);

    if (operation !== undefined) {
      operations.push(operation);

      const plan = buildEndpointRemoval({
        operationId: operation,
        repo: input.repo,
      });
      edits.push(...plan.edits);

      continue;
    }

    const siblingRoute = file.replace(/\.routes\.spec\.ts$/, ".routes.ts");
    const isGeneratedSpec =
      file.endsWith(".routes.spec.ts") &&
      input.repo.exists(siblingRoute) &&
      parseMarkedOperation(input.repo.read(siblingRoute)) !== undefined;

    if (isGeneratedSpec) continue;
    if (isScaffoldTrio(file, content)) continue;
    if (input.force) continue;

    unmarked.push(file);
  }

  return { operations, edits, unmarked };
}

export function buildFeatureRemoval(input: RemoveFeatureInput): RemovePlan {
  const name = normalizeFeatureName(input.rawName);
  const dir = `src/features/${name}`;

  if (!input.repo.exists(dir)) {
    throw new Error(`Feature "${name}" does not exist`);
  }

  if (PROTECTED_FEATURES.includes(name) && !input.forceCore) {
    throw new Error(
      `Refusing to remove protected core feature "${name}"; pass --force-core to override`,
    );
  }

  const files = input.repo.list(dir);
  const artifacts = collectFeatureArtifacts({
    name,
    files,
    repo: input.repo,
    force: input.force,
  });

  if (artifacts.unmarked.length > 0) {
    throw new Error(
      `Feature "${name}" contains files that were not scaffolded: ${artifacts.unmarked.join(
        ", ",
      )}; pass --force to remove anyway`,
    );
  }

  const zoneEdits: RemovalEdit[] = input.repo.exists("eslint.config.mjs")
    ? [{ kind: "zone-block", path: "eslint.config.mjs", feature: name }]
    : [];

  return {
    kind: "feature",
    description: `feature ${name} (${String(files.length)} files)`,
    deleteFiles: files,
    removeDirectories: [dir],
    edits: [...artifacts.edits, ...zoneEdits],
    returnOperations: artifacts.operations,
    coveragePath: COVERAGE_PATH,
    nextSteps: [
      `Run \`npm run verify:ci\` to confirm the feature left the tree`,
    ],
  };
}

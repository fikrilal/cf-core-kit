import assert from "node:assert/strict";
import { test } from "node:test";

import {
  checkAdrIndex,
  checkMarkdownLinks,
  checkMigrationsDrift,
  checkProjectMap,
  checkTypesDrift,
  normalizeTypesContent,
  parseDrizzleConfig,
  parseMapEntries,
} from "./check.mjs";

const existsIn = (paths) => (path) => paths.includes(path);

test("project map: existing entries pass", () => {
  const entries = parseMapEntries(
    "## Architecture Map\n\n```text\nsrc/app.ts  composition root\ndocs/  docs\n```\n",
  );

  assert.deepEqual(entries, [
    { path: "src/app.ts", planned: false },
    { path: "docs/", planned: false },
  ]);
  assert.equal(
    checkProjectMap(entries, {
      topLevelDirs: ["docs"],
      srcChildDirs: [],
      exists: existsIn(["src/app.ts", "docs/"]),
    }).length,
    0,
  );
});

test("project map: missing entry fails unless marked planned", () => {
  const entries = [
    { path: "tools/parity/", planned: false },
    { path: "src/features/", planned: true },
  ];
  const violations = checkProjectMap(entries, {
    topLevelDirs: [],
    srcChildDirs: [],
    exists: () => false,
  });

  assert.equal(violations.length, 1);
  assert.match(violations[0].detail, /tools\/parity\//);
});

test("project map: unmapped top-level and src directories fail", () => {
  const violations = checkProjectMap(
    [{ path: "src/platform/", planned: false }],
    {
      topLevelDirs: ["scripts"],
      srcChildDirs: ["features"],
      exists: () => true,
    },
  );

  assert.deepEqual(
    violations.map((violation) => violation.detail),
    [
      "unmapped top-level directory: scripts/",
      "unmapped src directory: src/features/",
    ],
  );
});

test("markdown links: resolvable targets pass, external and anchors are skipped", () => {
  const files = [
    {
      path: "docs/README.md",
      content:
        "[a](../core/project-architecture.md) [b](https://example.com/x) [c](#anchor) [d](mailto:x@y.z)",
    },
  ];

  assert.equal(
    checkMarkdownLinks(files, existsIn(["core/project-architecture.md"]))
      .length,
    0,
  );
});

test("markdown links: fragments and escaping resolve, broken targets fail", () => {
  const files = [
    {
      path: "docs/a/README.md",
      content: "[x](./b.md#section) [y](missing.md)",
    },
  ];
  const violations = checkMarkdownLinks(files, existsIn(["docs/a/b.md"]));

  assert.equal(violations.length, 1);
  assert.match(violations[0].detail, /missing\.md/);
});

test("adr index: aligned index passes", () => {
  const index = "| [0001](./0001-a.md) | [0002](./0002-b.md) |";
  assert.equal(
    checkAdrIndex(index, ["0001-a.md", "0002-b.md", "template.md"], () => true)
      .length,
    0,
  );
});

test("adr index: unindexed files and dangling links fail", () => {
  const violations = checkAdrIndex(
    "| [0001](./0001-a.md) | [0099](./0099-gone.md) |",
    ["0001-a.md", "0002-b.md"],
    (path) => path === "docs/adr/0001-a.md",
  );

  assert.deepEqual(
    violations.map((violation) => violation.detail),
    ["ADR not indexed: 0002-b.md", "index link does not resolve: 0099-gone.md"],
  );
});

test("types drift: normalized equality passes, drift and probe errors fail", () => {
  assert.equal(checkTypesDrift({ drifted: false, error: undefined }).length, 0);
  assert.equal(checkTypesDrift({ drifted: true, error: undefined }).length, 1);
  assert.match(
    checkTypesDrift({ drifted: false, error: "boom" })[0].detail,
    /probe failed: boom/,
  );
});

test("types drift: normalization strips the volatile header and import path", () => {
  const content = [
    "/* eslint-disable */",
    "// Generated by Wrangler by running `wrangler types /tmp/x.d.ts` (hash: abc)",
    'mainModule: typeof import("../../src/worker");',
  ].join("\n");

  const normalized = normalizeTypesContent(content, [
    { from: "../../src/worker", to: "./src/worker" },
  ]);

  assert.equal(normalized.includes("Generated by Wrangler"), false);
  assert.equal(normalized.includes('import("./src/worker")'), true);
});

test("drizzle config: literal params parse, malformed content is rejected", () => {
  assert.deepEqual(
    parseDrizzleConfig(
      'defineConfig({ dialect: "sqlite", schema: "./s.ts", out: "./db/migrations" });',
    ),
    { dialect: "sqlite", schema: "./s.ts", out: "./db/migrations" },
  );
  assert.equal(
    parseDrizzleConfig("defineConfig({ dialect: env.DIALECT });"),
    undefined,
  );
});

test("migrations drift: clean probe passes, new files and probe errors fail", () => {
  const base = { before: ["0000_a.sql"], after: ["0000_a.sql"] };

  assert.equal(checkMigrationsDrift(base).length, 0);
  assert.match(
    checkMigrationsDrift({
      before: ["0000_a.sql"],
      after: ["0000_a.sql", "0001_b.sql"],
    })[0].detail,
    /0001_b\.sql/,
  );
  assert.match(
    checkMigrationsDrift({ ...base, error: "boom" })[0].detail,
    /probe failed: boom/,
  );
});
